"""Stage 05: pool retrieval candidates per query and draft relevance grades.

Design and rationale: `notebooks/05_eval_set_B.ipynb` and `docs/domain_brief_B.md`.

What this produces is a DRAFT, on purpose. Stage 05's design says the held-out labels
are made by hand, because Sude's LLM judge is later validated against them; labels
generated by rules or by an LLM would make that validation circular. So this script
writes to `eval/datasets/drafts/`, never to the frozen `queries_B.jsonl` /
`qrels_B.jsonl`. `scripts/label_eval_B.py` is the review tool that turns reviewed drafts
into those files.

Pooling, per query:
  - the fused hybrid candidate set (top `candidate_k`),
  - the top `per_arm` of the BM25 arm and of the vector arm, separately, so a chunk only
    one arm found is still judged,
  - every chunk in a target paper that matches all `answer_all` patterns, even if no arm
    retrieved it. Without this, a chunk the retriever misses is never labelled, and
    recall@20 silently measures agreement with the retriever instead of recall.

Draft grade rules (0-3 scale from contracts/eval_dataset_J.py). A first version graded
by keyword patterns alone and put 1,510 of 2,294 pooled chunks at grade 3: every chunk of
a method paper mentions its own method, so patterns cannot tell "answers the question"
from "is about the same paper". Grades now come from read judgments where they exist:
  judged  grade from `llm_draft_grades_B.json`, written after reading the query-focused
          view (`--view`). Still a draft: it is an LLM's reading, not a human label.
  1       target-paper chunk nobody read ("target:unread")
  1       survey chunk matching every `answer_all` pattern
  0       any other paper

Usage:
  .venv/Scripts/python.exe scripts/build_eval_drafts_B.py --view fr001-fr010   # read candidates
  .venv/Scripts/python.exe scripts/build_eval_drafts_B.py                      # write drafts
"""

from __future__ import annotations

import collections
import json
import re
from pathlib import Path
from typing import Any

import typer

from research_assistant.contracts.eval_dataset_J import EvalQuery, Qrel
from research_assistant.contracts.retrieval_J import Chunk
from research_assistant.retrieval.service_B import RetrievalService

app = typer.Typer(add_completion=False)

REPO = Path(__file__).resolve().parent.parent
DRAFTS = REPO / "eval" / "datasets" / "drafts"
SPECS = DRAFTS / "query_specs_B.json"
CHUNKS = REPO / "data" / "processed" / "chunks.jsonl"

RELATED_WORK = re.compile(r"related work|background|prior work|literature", re.I)
BROAD_GRADE3 = 8  # more grade-3 drafts than this for one query: patterns probably too loose

# `contracts.eval_dataset_J.EvalQuery.intent` is Sude's contract enum, but `shape` here
# (`query_specs_B.json`) is our own finer-grained domain taxonomy (docs/domain_brief_B.md)
# and stays -- it is kept verbatim in `notes` so nothing about it is lost, this table
# just maps it down to the coarser enum the contract and the gate actually read.
SHAPE_TO_INTENT: dict[str, str] = {
    "method_lookup": "method",
    "dataset_lookup": "factoid",
    "results_metrics": "factoid",
    "challenge_handling": "synthesis",
    "explainability_limitations": "synthesis",
    "comparison": "comparison",
    "unanswerable": "unanswerable",
}


def _norm(text: str) -> str:
    return " ".join(text.split())


def _matches_all(patterns: list[str], text: str) -> bool:
    return bool(patterns) and all(re.search(p, text, re.I) for p in patterns)


def _matches_any(patterns: list[str], text: str) -> bool:
    return any(re.search(p, text, re.I) for p in patterns)


def draft_grade(
    chunk: Chunk,
    spec: dict[str, Any],
    surveys: set[str],
    judged: dict[str, int],
) -> tuple[int, str]:
    """Apply the rules in the module docstring. Returns (grade, reason)."""
    if chunk.chunk_id in judged:
        return int(judged[chunk.chunk_id]), "llm_draft"
    if chunk.metadata.paper_id in spec["targets"]:
        return 1, "target:unread"
    if chunk.metadata.paper_id in surveys and _matches_all(
        spec.get("answer_all", []), _norm(chunk.text)
    ):
        return 1, "survey:answer_match"
    return 0, "non_target"


_WORD = re.compile(r"[a-z0-9][a-z0-9\-]+")
_STOP = set("""a an the of and or to in for on with is are was were be by from at as how what which
why does do did this that these those it its their they into when whose who whom than then""".split())


def _terms(text: str) -> set[str]:
    return {w for w in _WORD.findall(text.lower()) if w not in _STOP and len(w) > 2}


def focus_view(spec: dict[str, Any], candidates: list[Chunk], per_paper: int) -> list[tuple[Chunk, str]]:
    """Top chunks per target paper by query-term overlap, each with its two best sentences.

    This is what gets read to assign draft grades. Showing two query-focused sentences
    rather than whole chunks keeps a 50-query pass readable; the cost is that an answer
    phrased with none of the query's words can be missed, which is why unread target
    chunks default to grade 1 rather than 0.
    """
    qterms = _terms(spec["query"])
    out: list[tuple[Chunk, str]] = []
    for pid in spec["targets"]:
        mine = [c for c in candidates if c.metadata.paper_id == pid]
        scored = sorted(mine, key=lambda c: -len(qterms & _terms(c.text)))[:per_paper]
        for c in scored:
            body = _norm(c.text.split("\n", 1)[-1])
            sentences = re.split(r"(?<=[.!?])\s+", body)
            best = sorted(sentences, key=lambda t: -len(qterms & _terms(t)))[:2]
            out.append((c, " ... ".join(x[:220] for x in best)))
    return out


def by_paper_list(by_paper: dict[str, list[Chunk]], spec: dict[str, Any]) -> list[Chunk]:
    return [c for pid in spec["targets"] for c in by_paper.get(pid, [])]


def _parse_range(expr: str, ids: list[str]) -> list[str]:
    if "-" not in expr:
        return [expr]
    lo, hi = expr.split("-", 1)
    return [i for i in ids if lo <= i <= hi]

CANDIDATE_K_OPTION = typer.Option(20, help="Fused candidate set size to pool")
PER_ARM_OPTION = typer.Option(20, help="Top-n from each arm to pool separately")
VIEW_OPTION = typer.Option(
    "", help="Print the reading view for a query or range, e.g. fr001-fr010, and exit"
)
VIEW_PER_PAPER_OPTION = typer.Option(10, help="Chunks shown per target paper in --view")


@app.command()
def main(
    candidate_k: int = typer.Option(20, help="Fused candidate set size to pool"),
    per_arm: int = typer.Option(20, help="Top-n from each arm to pool separately"),
    view: str = typer.Option("", help="Print the reading view for a query or range, e.g. fr001-fr010, and exit"),
    view_per_paper: int = typer.Option(10, help="Chunks shown per target paper in --view"),
) -> None:
    spec_doc = json.loads(SPECS.read_text(encoding="utf-8"))
    judgments_path = DRAFTS / "llm_draft_grades_B.json"
    judgments: dict[str, dict[str, int]] = (
        json.loads(judgments_path.read_text(encoding="utf-8")) if judgments_path.exists() else {}
    )
    surveys = set(spec_doc.get("surveys", []))
    specs = spec_doc["queries"]

    chunk_lines = CHUNKS.read_text(encoding="utf-8").splitlines()
    chunks = [Chunk.model_validate_json(line) for line in chunk_lines if line.strip()]
    by_id = {c.chunk_id: c for c in chunks}
    by_paper: dict[str, list[Chunk]] = collections.defaultdict(list)
    for c in chunks:
        by_paper[c.metadata.paper_id].append(c)

    svc = RetrievalService()
    if view:
        wanted = set(_parse_range(view, [q["query_id"] for q in specs]))
        for spec in specs:
            if spec["query_id"] not in wanted:
                continue
            print(f"\n=== {spec['query_id']} [{spec['shape']}] {spec['query']}")
            for c, snippet in focus_view(spec, by_paper_list(by_paper, spec), view_per_paper):
                section = (c.metadata.section or "")[:40]
                print(
                    f"  {c.chunk_id} | {c.metadata.paper_id} | {section} | p{c.metadata.page}"
                )
                print(f"      {snippet}")
        return

    queries: list[EvalQuery] = []
    pool_rows: list[dict[str, Any]] = []
    report: list[dict[str, Any]] = []

    for spec in specs:
        query = EvalQuery(
            query_id=spec["query_id"],
            query=spec["query"],
            intent=SHAPE_TO_INTENT.get(spec["shape"], "factoid"),
            split="dev",
            notes=f"shape={spec['shape']}; targets=" + ",".join(spec["targets"]),
        )
        queries.append(query)

        sources: dict[str, set[str]] = collections.defaultdict(set)
        result = svc.search(spec["query"], candidate_k=candidate_k, top_k=candidate_k)
        for scored in result.results:
            sources[scored.chunk.chunk_id].add("hybrid")
        for cid, _ in svc.bm25_arm(spec["query"], per_arm):
            sources[cid].add("bm25")
        for cid, _ in svc.vector_arm(spec["query"], per_arm):
            sources[cid].add("vector")
        for cid in judgments.get(spec["query_id"], {}):
            sources[cid].add("read")

        grades = collections.Counter()
        retrieved_grade3 = 0
        for cid, srcs in sources.items():
            chunk = by_id.get(cid)
            if chunk is None:
                continue
            grade, reason = draft_grade(chunk, spec, surveys, judgments.get(spec["query_id"], {}))
            grades[grade] += 1
            if grade == 3 and srcs & {"hybrid", "bm25", "vector"}:
                retrieved_grade3 += 1
            pool_rows.append({
                "query_id": spec["query_id"],
                "chunk_id": cid,
                "paper_id": chunk.metadata.paper_id,
                "section": chunk.metadata.section,
                "page": chunk.metadata.page,
                "draft_grade": grade,
                "draft_reason": reason,
                "sources": sorted(srcs),
                "reviewed": False,
                "grade": None,
                "reviewer": None,
            })
        report.append({"query_id": spec["query_id"], "shape": spec["shape"], "pool": len(sources),
                       "g3": grades[3], "g2": grades[2], "g1": grades[1], "g0": grades[0],
                       "g3_retrieved": retrieved_grade3})

    DRAFTS.mkdir(parents=True, exist_ok=True)
    (DRAFTS / "queries_draft_B.jsonl").write_text(
        "".join(q.model_dump_json() + "\n" for q in queries), encoding="utf-8")
    (DRAFTS / "qrels_draft_B.jsonl").write_text(
        "".join(
            Qrel(
                query_id=r["query_id"],
                chunk_id=r["chunk_id"],
                grade=r["draft_grade"],
                # "draft" flags every row here as not-yet-human-reviewed, distinct from
                # a real labeler name -- `scripts/label_eval_B.py` overwrites this with
                # the actual reviewer once a row is reviewed (`r["reviewer"]` above).
                labeler="draft",
            ).model_dump_json()
            + "\n"
            for r in pool_rows
        ),
        encoding="utf-8")
    (DRAFTS / "pool_B.jsonl").write_text(
        "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in pool_rows), encoding="utf-8")

    print(f"{'query':7s} {'shape':27s} {'pool':>4s} {'g3':>3s} {'g2':>3s} {'g1':>3s} {'g0':>3s} {'g3ret':>5s}  flag")
    for r in report:
        flag = "NO_GRADE3" if r["g3"] == 0 else ("BROAD" if r["g3"] > BROAD_GRADE3 else "")
        print(f"{r['query_id']:7s} {r['shape']:27s} {r['pool']:4d} {r['g3']:3d} {r['g2']:3d} "
              f"{r['g1']:3d} {r['g0']:3d} {r['g3_retrieved']:5d}  {flag}")
    total = collections.Counter(row["draft_grade"] for row in pool_rows)
    print(f"\nqueries {len(queries)}  pool rows {len(pool_rows)}  "
          f"grades 3:{total[3]} 2:{total[2]} 1:{total[1]} 0:{total[0]}")
    print(f"wrote {DRAFTS.relative_to(REPO)}/queries_draft_B.jsonl, qrels_draft_B.jsonl, pool_B.jsonl")


if __name__ == "__main__":
    app()
